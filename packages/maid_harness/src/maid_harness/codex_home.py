"""A clean, isolated CODEX_HOME for sub-agents, derived from the user's live ~/.codex before every run.

  kept from ~/.codex/config.toml   provider and login settings only (KEEP below)
  linked                           auth.json -> ~/.codex/auth.json  (never copied, never read here)
  dropped                          mcp_servers, notify, hooks, skills, plugins, projects, features, model, ...
  ours                             model, effort, filesystem permission profile

Because it is rebuilt from the live files on every launch, switching provider or account with a tool that
rewrites ~/.codex (cc-switch) applies to the next sub-agent run. Sessions, logs and caches of sub-agents
stay in this home, so they never mix with the user's own Codex sessions. `fingerprint()` says which
provider/account a run used without revealing anything: a short hash, not the content.
"""

from __future__ import annotations

import hashlib
import json
import os
import tomllib
from pathlib import Path
from urllib.parse import urlparse

KEEP = ("model_provider", "model_providers", "preferred_auth_method", "cli_auth_credentials_store",
        "forced_login_method", "forced_chatgpt_workspace_id", "chatgpt_base_url", "openai_base_url")
LINKED = ("auth.json",)
# Codex features a sub-agent never needs. apps alone stalled startup ~35 s reaching the ChatGPT connector;
# multi_agent would let a sub-agent spawn more agents on the user's account. Checked on codex-cli 0.165.0.
FEATURES_OFF = ("apps", "plugins", "remote_plugin", "plugin_sharing", "browser_use", "browser_use_external",
                "browser_use_full_cdp_access", "computer_use", "image_generation", "in_app_browser", "in_app_chat",
                "in_app_dictation", "in_app_local_automation", "in_app_voice", "multi_agent", "goals", "hooks",
                "skill_search", "skill_mcp_dependency_install", "tool_suggest", "daemon_auto_start",
                "guardian_approval")


def _toml_value(v) -> str:
    if isinstance(v, bool):
        return "true" if v else "false"
    if isinstance(v, (int, float)):
        return repr(v)
    if isinstance(v, str):
        return json.dumps(v)
    if isinstance(v, list):
        return "[" + ", ".join(_toml_value(x) for x in v) + "]"
    raise TypeError(f"unsupported TOML value {v!r}")


def _toml_key(k: str) -> str:
    return k if k.replace("_", "").replace("-", "").isalnum() else json.dumps(k)


def dump_toml(data: dict, prefix: str = "") -> str:
    """Enough TOML for a Codex config: scalars, lists, nested tables."""
    lines, tables = [], []
    for k, v in data.items():
        if isinstance(v, dict):
            tables.append((k, v))
        else:
            lines.append(f"{_toml_key(k)} = {_toml_value(v)}")
    out = "\n".join(lines)
    for k, v in tables:
        name = f"{prefix}.{_toml_key(k)}" if prefix else _toml_key(k)
        out += f"\n\n[{name}]\n" + dump_toml(v, name)
    return out.strip() + "\n"


def build_codex_home(home: Path, model: str = "", effort: str = "low", source: Path | None = None,
                     permissions: dict | None = None) -> dict:
    """(Re)write `home` from `source` (default ~/.codex). Returns the fingerprint of what it points at."""
    source = source or Path(os.environ.get("MAID_USER_CODEX_HOME", Path.home() / ".codex"))
    home.mkdir(parents=True, exist_ok=True)
    user = tomllib.loads((source / "config.toml").read_text()) if (source / "config.toml").exists() else {}
    cfg = {k: user[k] for k in KEEP if k in user}
    if model:
        cfg["model"] = model
    cfg["model_reasoning_effort"] = effort
    cfg["check_for_update_on_startup"] = False
    cfg["features"] = {name: False for name in FEATURES_OFF}
    if permissions:
        cfg["default_permissions"] = "maid"
        cfg["permissions"] = {"maid": permissions}
    tmp = home / "config.toml.tmp"
    tmp.write_text("# generated by maid_harness.codex_home from the user's ~/.codex; do not edit\n" + dump_toml(cfg))
    tmp.replace(home / "config.toml")
    for name in LINKED:
        link, target = home / name, source / name
        if link.is_symlink() or link.exists():
            if link.is_symlink() and os.readlink(link) == str(target):
                continue
            link.unlink()
        if target.exists():
            link.symlink_to(target)
    return fingerprint(home, cfg)


def fingerprint(home: Path, cfg: dict | None = None) -> dict:
    """Which provider, endpoint, model and account a run uses, safe to log: hashes, never secrets."""
    cfg = cfg if cfg is not None else tomllib.loads((home / "config.toml").read_text())
    name = cfg.get("model_provider", "openai")
    provider = (cfg.get("model_providers") or {}).get(name, {})
    base = str(provider.get("base_url", ""))
    base = base or str(cfg.get("openai_base_url", ""))
    return {"provider": name, "endpoint": urlparse(base).hostname if base else "default",
            "model": cfg.get("model", ""), "effort": cfg.get("model_reasoning_effort", ""),
            "account": _account_id(home / "auth.json")}


def _account_id(auth: Path) -> str | None:
    """A short hash of *which* account (API key or ChatGPT account id), stable across token refreshes."""
    if not auth.exists():
        return None
    try:
        d = json.loads(auth.read_text())
        ident = d.get("OPENAI_API_KEY") or (d.get("tokens") or {}).get("account_id") or ""
    except (OSError, ValueError):
        ident = ""
    return hashlib.sha256(str(ident).encode()).hexdigest()[:10] if ident else "unknown"
